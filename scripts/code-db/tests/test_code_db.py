class RustTestTagTest(unittest.TestCase):
    def test_cfg_and_attribute_forms(self):
        data = b"""#[cfg(all(test, feature = "x"))]
mod a {}
#[cfg(not(test))]
mod b {}
#[tokio::test]
/// Doc comment between attribute and item.
#[ignore]
async fn c() {}
fn d() {}
"""
        g = syntax.grammar("rust", ".rs")
        tree = g.parse(data)
        tagged = {data[n.start_byte:n.end_byte].split(b"\n")[-1] for n in walk(tree.root_node)
                  for node_id, tag in syntax.tags(g, tree, "src/lib.rs") if tag == "test" and n.id == node_id}
        self.assertEqual(tagged, {b"mod a {}", b"async fn c() {}"})
        root = {tag for node_id, tag in syntax.tags(g, tree, "crates/x/tests/it.rs") if node_id == tree.root_node.id}
        self.assertEqual(root, {"test"})


def walk(node):
    yield node
    for child in node.children:
        yield from walk(child)


class ClonePathTest(unittest.TestCase):
    def test_absolute_and_unknown_paths(self):
        root = Path("/repo")
        self.assertEqual(clones.repo_path("/repo/src/a.rs", root, {"src/a.rs"}), "src/a.rs")
        with self.assertRaises(ValueError):
            clones.repo_path("a.rs", root, {"src/a.rs"})  # relative to a scan root, not the repository
        self.assertEqual([l for l, _ in clones.parse_specs(["x/exact/jscpd-report.json", "x/norm/jscpd-report.json"])],
                         ["exact", "norm"])
        with self.assertRaises(ValueError):
            clones.parse_specs(["a/jscpd-report.json", "a/jscpd-report.json"])


def varint(value):
    value &= (1 << 64) - 1
    out = bytearray()
    while True:
        byte = value & 0x7F
        value >>= 7
        if value:
            out.append(byte | 0x80)
        else:
            out.append(byte)
            return bytes(out)


def field(number, payload):
    if isinstance(payload, int):
        return varint(number << 3) + varint(payload)
    return varint(number << 3 | 2) + varint(len(payload)) + payload


def symbol_message(item):
    kinds = {v: k for k, v in scip.KINDS.items()}
    return (field(1, item["symbol"].encode()) + field(5, kinds[item["kind"]])
            + field(6, item["display_name"].encode()))


def encode_index(documents, external):
    """Encode with the legacy packed range for some occurrences and typed ranges for others."""
    out = b""
    for doc in documents:
        body = field(1, doc["path"].encode())
        for i, occ in enumerate(doc["occurrences"]):
            sl, sc, el, ec = occ["range"]
            if i % 2:
                rng = field(9, field(1, sl) + field(2, sc) + field(3, el) + field(4, ec))
            else:
                values = [sl, sc, ec] if sl == el else [sl, sc, el, ec]
                rng = field(1, b"".join(varint(v) for v in values))
            message = rng + field(2, occ["symbol"].encode()) + (field(3, occ["roles"]) if occ["roles"] else b"")
            body += field(2, message)
        for item in doc["symbols"]:
            body += field(3, symbol_message(item))
        out += field(2, body)
    for item in external:
        out += field(3, symbol_message(item))
    return out


