        self.assertEqual(self.tags("pkg/calc_test.go"), {("test", "source_file"), ("test", "function_declaration")})
        self.assertEqual(self.tags("gen.go"), {("generated_or_macro", "source_file")})
        self.assertEqual(self.tags("calc.ts"), {("test", "call_expression")})
        self.assertEqual(self.tags("calc.test.ts"), {
            ("test", "program"), ("generated_or_macro", "program"), ("test", "call_expression")})
