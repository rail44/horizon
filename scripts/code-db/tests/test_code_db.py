def git(repo, *args, date="2026-01-05T00:00:00Z"):
    env = {
        **os.environ, "GIT_CONFIG_GLOBAL": os.devnull, "GIT_CONFIG_NOSYSTEM": "1",
        "GIT_AUTHOR_DATE": date, "GIT_COMMITTER_DATE": date,
    }
    return subprocess.run(
        ["git", "-c", "user.name=Fixture Author", "-c", "user.email=fixture@example.invalid",
         "-c", "commit.gpgsign=false", *args],
        cwd=repo, env=env, check=True, capture_output=True, text=True).stdout


def make_repo(repo):
    git(repo, "init", "-q", "-b", "main")
    for date, message, files in COMMITS:
        for name, text in files.items():
            (repo / name).write_text(text)
        git(repo, "add", "-A")
        git(repo, "commit", "-q", "-m", message, date=date)
    (repo / "pkg").mkdir()
    git(repo, "mv", "calc.go", "pkg/calc.go")
    git(repo, "mv", "calc_test.go", "pkg/calc_test.go")
    git(repo, "commit", "-q", "-m", "Move Go sources", date="2026-01-05T00:00:00Z")
    return git(repo, "rev-parse", "HEAD").strip()


class CodeDbTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.TemporaryDirectory(prefix="code-db-test-")
        cls.repo = Path(cls.tmp.name) / "repo"
        cls.repo.mkdir()
        cls.head = make_repo(cls.repo)
        cls.db = Path(cls.tmp.name) / "out" / "fixture.duckdb"
        with contextlib.redirect_stdout(io.StringIO()):
            status = build.main([
                "build", str(cls.repo), "--out", str(cls.db),
                "--clones", f"fixture={FIXTURES / 'jscpd-report.json'}",
                "--scip", str(FIXTURES / "index.scip.json"),
            ])
        assert status == 0, "fixture build failed"
        cls.con = duckdb.connect(str(cls.db), read_only=True)

    @classmethod
    def tearDownClass(cls):
        cls.con.close()
        cls.tmp.cleanup()

    def rows(self, sql, params=None):
        return self.con.execute(sql, params or []).fetchall()

    def query(self, name, *params):
        columns, rows = build.run_query(self.db, name, params)
        return [dict(zip(columns, row)) for row in rows]

    def units(self, path):
        return set(self.rows(
            "SELECT u.kind, u.qualified_name FROM units u JOIN files f USING (file_id) WHERE f.path = ?", [path]))

    def tags(self, path):
        return set(self.rows(
            "SELECT t.tag, n.kind FROM tags t JOIN nodes n USING (file_id, node_id) JOIN files f USING (file_id) "
            "WHERE f.path = ?", [path]))

    def test_files_and_nodes(self):
        files = dict(self.rows("SELECT path, language FROM files"))
        self.assertEqual(files, {
            "lib.rs": "rust", "pkg/calc.go": "go", "pkg/calc_test.go": "go", "gen.go": "go",
            "calc.ts": "typescript", "calc.test.ts": "typescript"})
        root = self.rows("SELECT n.kind, n.parent_id, n.depth, n.end_byte, f.size_bytes FROM nodes n "
                         "JOIN files f USING (file_id) WHERE f.path = 'lib.rs' AND n.node_id = 0")
        self.assertEqual(root, [("source_file", None, 0, len(RUST_V4.encode()), len(RUST_V4.encode()))])
        orphans = self.rows("SELECT count(*) FROM nodes c LEFT JOIN nodes p ON p.file_id = c.file_id "
                            "AND p.node_id = c.parent_id WHERE c.parent_id IS NOT NULL AND p.node_id IS NULL")
        self.assertEqual(orphans, [(0,)])
        blob = self.rows("SELECT blob_sha FROM files WHERE path = 'lib.rs'")[0][0]
        self.assertEqual(blob, git(self.repo, "rev-parse", "HEAD:lib.rs").strip())

    def test_units_per_language(self):
        self.assertEqual(self.units("lib.rs"), {
            ("function", "alpha"), ("function", "beta"), ("type", "Meter"),
            ("impl", "std::fmt::Display for Meter"), ("method", "std::fmt::Display for Meter.fmt"),
            ("module", "tests"), ("function", "tests.adds")})
        self.assertEqual(self.units("pkg/calc.go"), {
            ("type", "Meter"), ("method", "Meter.Read"), ("function", "Alpha"), ("function", "Beta"),
            ("function", "TestAlpha")})
        self.assertEqual(self.units("calc.ts"), {
            ("function", "alpha"), ("function", "beta"), ("type", "Meter"), ("method", "Meter.read"),
            ("function", "gammaTs")})
        alpha = self.rows("SELECT u.start_row, u.end_row, u.loc, u.parent_unit_id FROM units u "
                          "JOIN files f USING (file_id) WHERE f.path = 'lib.rs' AND u.name = 'alpha'")
        self.assertEqual(alpha, [(0, 6, 7, None)])
        nested = self.rows("SELECT p.qualified_name FROM units u JOIN units p ON p.unit_id = u.parent_unit_id "
                           "WHERE u.qualified_name = 'tests.adds'")
        self.assertEqual(nested, [("tests",)])

